# v3.9: octava rápida (Alt ↓ / Alt ↑ y botones) y portapapeles de etiquetas (V, Mayús V, grupos, selección).
# Uso: python3 tests/quick_ui.py [Circuit_Tracks_Patch_Library_Editor.html]  (antes: node tests/make-fixtures.mjs)
import sys, os, re, threading, http.server, functools
from playwright.sync_api import sync_playwright
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
FAKE_MIDI = re.search(r'FAKE_MIDI = """(.*?)"""', open(os.path.join(ROOT, 'tests', 'browser_test.py')).read(), re.S).group(1)
FILE = sys.argv[1] if len(sys.argv) > 1 else 'Circuit_Tracks_Patch_Library_Editor.html'
EN = '_EN' in FILE
class Q(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 8783), functools.partial(Q, directory=os.path.join(ROOT, 'dist'))); threading.Thread(target=srv.serve_forever, daemon=True).start()
res = []; errors = []
def ok(name, cond, extra=''): res.append(bool(cond)); print(('PASS ' if cond else 'FAIL ') + name + (' · ' + str(extra) if extra != '' else ''))
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    ctx = b.new_context(viewport={'width': 1500, 'height': 1000}); ctx.add_init_script(FAKE_MIDI)
    pg = ctx.new_page(); pg.on('pageerror', lambda e: errors.append(str(e)))
    pg.on('console', lambda m: errors.append('console: ' + m.text) if m.type == 'error' else None)
    pg.goto('http://127.0.0.1:8783/' + FILE); pg.wait_for_selector('.top .brand')
    pg.set_input_files('#dirIn', os.path.join(ROOT, 'tests', 'out')); pg.wait_for_selector('.modal', timeout=60000); pg.click('.modal .btn'); pg.wait_for_timeout(300)
    J = lambda js: pg.evaluate(js)
    pg.click('.tabs-main button[data-v="device"]'); pg.click('button[data-act="midiConnect"]'); pg.wait_for_timeout(300)
    pg.click('.tabs-main button[data-v="audition"]'); pg.wait_for_timeout(300)
    base = J('window.__ctpl.S.queue[window.__ctpl.S.qi]')
    st = lambda: J(f"(() => {{ const L = window.__ctpl.lib, b = L.byId('{base}'), v = L.currentVersion(b); return {{ id: v.id, q: v.meta.quickOct || 0, n: L.patches.filter((x) => x.parentId === '{base}' && x.meta.quickOct).length, pl: Array.from(v.payload), adopted: L.changeState ? L.changeState(v) : '' }}; }})()")
    s0 = st()
    ok('Escucha: botones −8va / +8va', pg.locator('.octq [data-act="qOct"]').count() >= 2)
    J('window.__midiSent.length = 0')
    pg.keyboard.press('Alt+ArrowDown'); pg.wait_for_timeout(500)
    s1 = st()
    ok('Alt ↓: una octava más grave, como versión aceptada', s1['q'] == -12 and s1['id'] != base and s1['pl'] != s0['pl'], s1['q'])
    sent = J('window.__midiSent')
    ok('y suena al momento con el patch nuevo', any(a[0] == 0xF0 and len(a) == 350 and a[-341:-1] == s1['pl'] for a in sent) and any((a[0] & 0xF0) == 0x90 for a in sent))
    ok('La etiqueta dice «−1 oct»', '−1 oct' in pg.locator('.octq b').first.inner_text())
    pg.keyboard.press('Alt+ArrowDown'); pg.wait_for_timeout(500)
    s2 = st()
    ok('Otra vez: se suma en la misma versión (−2 oct, sin variantes encadenadas)', s2['q'] == -24 and s2['id'] == s1['id'] and s2['n'] == 1, (s2['q'], s2['n']))
    J('window.__midiSent.length = 0')
    pg.keyboard.press('Space'); pg.wait_for_timeout(400)
    ok('Espacio en Escucha toca la versión con la octava cambiada', any(a[0] == 0xF0 and len(a) == 350 and a[-341:-1] == s2['pl'] for a in J('window.__midiSent')))
    pg.keyboard.press('Alt+ArrowUp'); pg.wait_for_timeout(400); pg.keyboard.press('Alt+ArrowUp'); pg.wait_for_timeout(500)
    s3 = st()
    ok('Volver a la octava original quita la versión', s3['id'] == base and s3['q'] == 0 and s3['n'] == 0 and s3['pl'] == s0['pl'])
    # en la ficha de la Biblioteca, con botón
    pg.click('.tabs-main button[data-v="library"]'); J(f"(() => {{ window.__ctpl.S.sel = '{base}'; }})()"); pg.click('.tabs-main button[data-v="library"]'); pg.wait_for_timeout(300)
    pg.click('.center [data-act="qOct"][data-n="12"]'); pg.wait_for_timeout(500)
    s4 = st()
    ok('Biblioteca: +8va en la ficha', s4['q'] == 12 and s4['n'] == 1)
    pg.reload(); pg.wait_for_selector('.top .brand'); pg.wait_for_timeout(600)
    ok('Sigue así al recargar', st()['q'] == 12)

    # ---------- portapapeles de etiquetas ----------
    pg.click('.tabs-main button[data-v="audition"]'); pg.wait_for_timeout(300)
    tags = lambda pid: J(f"window.__ctpl.lib.byId('{pid}').meta.tags || []")
    pid = lambda: J('window.__ctpl.S.queue[window.__ctpl.S.qi]')
    ok('Escucha: portapapeles de etiquetas', pg.locator('.tclip').count() == 1)
    pg.fill('#clipIn', 'Wobble'); pg.press('#clipIn', 'Enter'); pg.wait_for_timeout(300)
    ok('Escribir «Wobble» lo pone en el portapapeles', J('window.__ctpl.lib.settings.tagClip') == ['Wobble'])
    pg.locator('body').click(position={'x': 5, 'y': 400}); pg.wait_for_timeout(100)
    a = pid(); pg.keyboard.press('v'); pg.wait_for_timeout(400)
    ok('V lo pega en el que escuchas', 'Wobble' in tags(a))
    pg.keyboard.press('ArrowRight'); pg.wait_for_timeout(300)
    b2 = pid(); pg.keyboard.press('v'); pg.wait_for_timeout(400)
    ok('y en el siguiente con otra V', b2 != a and 'Wobble' in tags(b2))
    ok('El botón dice «Ya las tiene»', ('already has them' if EN else 'ya las tiene') in pg.locator('[data-act="clipPaste"]').inner_text().lower())
    J(f"window.__ctpl.lib.addTags(['{b2}'], ['Dark', 'Acid'])"); pg.wait_for_timeout(200)
    pg.keyboard.press('Shift+V'); pg.wait_for_timeout(400)
    ok('Mayús V copia las etiquetas del patch', sorted(J('window.__ctpl.lib.settings.tagClip')) == ['Acid', 'Dark', 'Wobble'])
    pg.click('[data-act="clipGroup"]'); pg.wait_for_timeout(300)
    pg.click('[data-act="clipClear"]'); pg.wait_for_timeout(300)
    ok('Guardar como grupo y vaciar', J('window.__ctpl.lib.settings.tagGroups').__len__() == 1 and J('window.__ctpl.lib.settings.tagClip') == [])
    pg.click('[data-act="clipLoad"]'); pg.wait_for_timeout(300)
    ok('Cargar el grupo con un clic', sorted(J('window.__ctpl.lib.settings.tagClip')) == ['Acid', 'Dark', 'Wobble'])
    # selección en la Biblioteca
    ids = J("window.__ctpl.lib.patches.filter((p) => p.kind === 'original').slice(10, 13).map((p) => p.id)")
    J(f"(() => {{ const S = window.__ctpl.S; S.view = 'library'; S.multi = new Set({ids}); S.sel = '{ids[0]}'; }})()"); pg.click('.tabs-main button[data-v="library"]'); pg.wait_for_timeout(300)
    ok('Biblioteca con 3 seleccionados: «Pegar en 3»', ('paste on 3' if EN else 'pegar en 3') in pg.locator('[data-act="clipPaste"]').first.inner_text().lower())
    pg.click('[data-act="clipPaste"] >> nth=0'); pg.wait_for_timeout(400)
    ok('y se pegan en los tres', all(set(['Acid', 'Dark', 'Wobble']) <= set(tags(i)) for i in ids))
    pg.reload(); pg.wait_for_selector('.top .brand'); pg.wait_for_timeout(500)
    ok('Portapapeles y grupos siguen al recargar', len(J('window.__ctpl.lib.settings.tagClip')) == 3 and len(J('window.__ctpl.lib.settings.tagGroups')) == 1)
    ok('Sin errores de JavaScript', not errors, ' | '.join(errors[:3]))
    b.close()
srv.shutdown()
print(f'{sum(res)}/{len(res)} comprobaciones superadas')
sys.exit(0 if all(res) else 1)
